import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';
import PDFDocument from 'pdfkit';
import { db } from '../../db.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

export function getFont() {
  const fontPath = path.join(__dirname, '../../fonts', 'NotoSansCJKjp-Regular.otf');
  if (fs.existsSync(fontPath)) return fontPath;
  return null;
}

export function streamCvPdf(profile, res) {
  const doc = new PDFDocument({
    size: 'A4',
    margin: 50,
    info: { Title: 'Rirekisho - ' + profile.name },
  });
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="rirekisho-${profile.name.replace(/\s+/g, '_')}.pdf"`
  );
  doc.pipe(res);

  const font = getFont();
  if (font) {
    doc.registerFont('jp', font);
    doc.font('jp');
  }

  doc.fontSize(20).text('履歴書 (Rirekisho)', { align: 'center' });
  doc.moveDown(0.5);
  doc.fontSize(16).text(profile.nameJp || profile.name, { align: 'center' });
  if (profile.nameJp) doc.fontSize(12).text(profile.name, { align: 'center' });
  doc.moveDown();

  doc.fontSize(11);
  const row = (label, value) => {
    if (!value) return;
    doc.text(label + ': ' + value);
  };
  row('Email', profile.email);
  row('Telepon / 電話', profile.phone);
  row('Asal / 出身', profile.originCity);
  row('JLPT', profile.jlptLevel);
  row(
    'Spesialisasi / 専門',
    Array.isArray(profile.specialization)
      ? profile.specialization.join(', ')
      : profile.specialization
  );
  doc.moveDown();

  if (profile.education && profile.education.length) {
    doc.fontSize(13).text('学歴 / Pendidikan');
    doc.moveDown(0.3);
    doc.fontSize(10);
    profile.education.forEach((e) =>
      doc.text(`• ${e.year || ''} — ${e.degree || ''} — ${e.institution || ''}`)
    );
    doc.moveDown();
  }

  if (profile.experience && profile.experience.length) {
    doc.fontSize(13).text('職歴 / Pengalaman Kerja');
    doc.moveDown(0.3);
    doc.fontSize(10);
    profile.experience.forEach((x) =>
      doc.text(
        `• ${x.start || ''} – ${x.end || 'sekarang'} — ${x.title || ''} @ ${x.company || ''}`
      )
    );
    doc.moveDown();
  }

  if (profile.bioJp || profile.bioId) {
    doc.fontSize(13).text('自己紹介 / Bio');
    doc.moveDown(0.3);
    doc.fontSize(10);
    if (profile.bioJp) doc.text('JP: ' + profile.bioJp);
    if (profile.bioId) doc.text('ID: ' + profile.bioId);
    doc.moveDown();
  }

  doc
    .fontSize(8)
    .fillColor('#888')
    .text(`Generated by JITA pada ${new Date().toLocaleString('id-ID')}`, { align: 'right' });
  doc.end();
}

import { NotFoundError } from '../../errors/AppError.js';

export const cvService = {
  getFont,
  streamCvPdf,

  async getProfileForCv(userId) {
    const [rows] = await db.query('SELECT * FROM users WHERE id = ?', [userId]);
    if (rows.length === 0) throw new NotFoundError('User tidak ditemukan');
    const u = rows[0];
    return {
      name: u.name,
      nameJp: u.name_jp,
      email: u.email,
      phone: u.phone,
      originCity: u.origin_city,
      jlptLevel: u.jlpt_level,
      specialization: u.specialization ? u.specialization.split(',').map((s) => s.trim()) : [],
      education:
        typeof u.education_json === 'string'
          ? JSON.parse(u.education_json || '[]')
          : u.education_json || [],
      experience:
        typeof u.experience_json === 'string'
          ? JSON.parse(u.experience_json || '[]')
          : u.experience_json || [],
      bioId: u.bio_id,
      bioJp: u.bio_jp,
      profile_verified: u.profile_verified,
    };
  },
};

export default cvService;
